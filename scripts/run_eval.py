"""Run the evaluation from the command line and write a Markdown report.

Usage:
    python scripts/run_eval.py                      # both engines x both datasets
    python scripts/run_eval.py --dataset synthetic --engine baseline --n 500
    python scripts/run_eval.py --no-save            # don't store the run in SQLite

Output:
    reports/results.md   human-readable tables (linked from the README)
    reports/results.json full machine-readable report
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from app.config import REPORTS_DIR  # noqa: E402
from app.datasets import DATASETS, load_dataset  # noqa: E402
from app.evaluator import evaluate  # noqa: E402
from app.redactor import ENGINES, get_redactor  # noqa: E402
from app.storage import save_run  # noqa: E402


def _pct(x: float) -> str:
    return f"{x * 100:.1f}%"


def to_markdown(report: dict) -> str:
    o = report["overall"]
    lines = [
        f"### {report['dataset']} / {report['engine']} ({report['n_samples']} samples, {report['seconds']}s)",
        "",
        f"**Overall:** precision {_pct(o['precision'])}, recall {_pct(o['recall'])}, F1 {_pct(o['f1'])} "
        f"(TP {o['tp']}, FP {o['fp']}, FN {o['fn']})",
        "",
        "| Entity type | Support | Precision | Recall | F1 | Missed (FN) | False alarms (FP) |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for t in report["per_type"]:
        if t["support"] == 0 and t["fp"] == 0:
            continue
        lines.append(
            f"| {t['entity_type']} | {t['support']} | {_pct(t['precision'])} | {_pct(t['recall'])} "
            f"| {_pct(t['f1'])} | {t['fn']} | {t['fp']} |"
        )
    if report["misses"]:
        lines += ["", "<details><summary>Examples of missed PII</summary>", "",
                  "| Type | Missed value | Why it's hard |", "|---|---|---|"]
        for m in report["misses"][:15]:
            value = m["value"].replace("|", "\\|")
            lines.append(f"| {m['entity_type']} | `{value}` | {m.get('note') or ''} |")
        lines += ["", "</details>"]
    return "\n".join(lines)


def comparison_table(reports: list[dict]) -> str:
    lines = ["| Dataset | Engine | Precision | Recall | F1 | Missed PII | False alarms |",
             "|---|---|---:|---:|---:|---:|---:|"]
    for r in reports:
        o = r["overall"]
        lines.append(f"| {r['dataset']} | {r['engine']} | {_pct(o['precision'])} | {_pct(o['recall'])} "
                     f"| {_pct(o['f1'])} | {o['fn']} | {o['fp']} |")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--dataset", choices=[*DATASETS, "all"], default="all")
    parser.add_argument("--engine", choices=[*ENGINES, "all"], default="all")
    parser.add_argument("--n", type=int, default=300, help="Synthetic sample count")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--no-save", action="store_true")
    args = parser.parse_args()

    datasets = DATASETS if args.dataset == "all" else (args.dataset,)
    engines = list(ENGINES) if args.engine == "all" else [args.engine]
    reports = []
    for name in datasets:
        samples = load_dataset(name, n=args.n, seed=args.seed)
        if not samples:
            print(f"Skipping {name}: no samples")
            continue
        for engine in engines:
            report = evaluate(get_redactor(engine), samples, dataset=name).to_dict()
            if not args.no_save:
                report["run_id"] = save_run(report)
            reports.append(report)
            o = report["overall"]
            print(f"{name:<11} {engine:<9} precision {_pct(o['precision'])}  "
                  f"recall {_pct(o['recall'])}  F1 {_pct(o['f1'])}")

    REPORTS_DIR.mkdir(exist_ok=True)
    md = ("# Evaluation results\n\n"
          f"Generated by `python scripts/run_eval.py` ({args.n} synthetic samples, seed {args.seed}). "
          "spaCy model: `en_core_web_sm`.\n\n"
          "## Summary\n\n" + comparison_table(reports) + "\n\n## Details\n\n")
    md += "\n\n".join(to_markdown(r) for r in reports) + "\n"
    (REPORTS_DIR / "results.md").write_text(md, encoding="utf-8")
    (REPORTS_DIR / "results.json").write_text(json.dumps(reports, indent=2), encoding="utf-8")
    print(f"Report written to {REPORTS_DIR / 'results.md'}")


if __name__ == "__main__":
    main()
